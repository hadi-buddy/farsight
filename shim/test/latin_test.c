// Tests for persian_to_latin (latin.js port). Build and run: shim/test/itn_test.sh
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "../persian_latin.h"

static int fails;

static void check(const char *in, const char *want) {
  char *got = persian_to_latin(in);
  if (strcmp(got, want) != 0) {
    printf("FAIL\n  in:   %s\n  want: %s\n  got:  %s\n", in, want, got);
    fails++;
  }
  free(got);
}

int main(void) {
  // Single-word curated terms.
  check("\xd8\xb1\xdb\x8c\xd9\xbe\xd9\x88 \xd8\xb1\xd9\x88 \xda\x86\xda\xa9 \xda\xa9\xd9\x86",
        "repo \xd8\xb1\xd9\x88 \xda\x86\xda\xa9 \xda\xa9\xd9\x86");  // ریپو رو چک کن -> repo رو چک کن
  check("\xda\xaf\xdb\x8c\xd8\xaa \xd9\x87\xd8\xa7\xd8\xa8 \xd8\xb1\xd9\x88 \xda\x86\xda\xa9 \xda\xa9\xd9\x86",
        "GitHub \xd8\xb1\xd9\x88 \xda\x86\xda\xa9 \xda\xa9\xd9\x86");  // گیت هاب رو چک کن -> GitHub رو چک کن
  check("\xd8\xac\xd8\xa7\xd9\x88\xd8\xa7\xd8\xa7\xd8\xb3\xda\xa9\xd8\xb1\xdb\x8c\xd9\xbe\xd8\xaa",
        "JavaScript");  // جاوااسکریپت

  // Multi-word term beats the single-word one at the same position.
  check("\xd9\xbe\xd9\x88\xd9\x84 \xd8\xb1\xdb\x8c\xda\xa9\xd9\x88\xd8\xa6\xd8\xb3\xd8\xaa \xd8\xb1\xd9\x88 \xd8\xa8\xd8\xa7\xd8\xb2 \xda\xa9\xd9\x86",
        "pull request \xd8\xb1\xd9\x88 \xd8\xa8\xd8\xa7\xd8\xb2 \xda\xa9\xd9\x86");  // پول ریکوئست رو باز کن

  // Suffix glued to the English word.
  check("\xda\xa9\xd8\xa7\xd9\x85\xdb\x8c\xd8\xaa\xd9\x87\xd8\xa7 \xd8\xb1\xd9\x88 \xda\x86\xda\xa9 \xda\xa9\xd9\x86",
        "commit\xe2\x80\x8c\xd9\x87\xd8\xa7 \xd8\xb1\xd9\x88 \xda\x86\xda\xa9 \xda\xa9\xd9\x86");  // کامیتها -> commit‌ها

  // Light-verb phrase: "پوش کن" -> "push کن".
  check("\xd8\xa7\xdb\x8c\xd9\x86 \xd9\x81\xd8\xa7\xdb\x8c\xd9\x84 \xd8\xb1\xd9\x88 \xd9\xbe\xd9\x88\xd8\xb4 \xda\xa9\xd9\x86",
        "\xd8\xa7\xdb\x8c\xd9\x86 \xd9\x81\xd8\xa7\xdb\x8c\xd9\x84 \xd8\xb1\xd9\x88 push \xda\xa9\xd9\x86");  // این فایل رو پوش کن

  // "پول" (money) is ordinary Persian outside a light-verb phrase and
  // outside "pull request" -- stays Persian.
  check("\xd9\xbe\xd9\x88\xd9\x84 \xd9\x86\xd8\xaf\xd8\xa7\xd8\xb1\xd9\x85",
        "\xd9\xbe\xd9\x88\xd9\x84 \xd9\x86\xd8\xaf\xd8\xa7\xd8\xb1\xd9\x85");  // پول ندارم

  // "هرج و مرج" idiom: "مرج" must NOT become "merge" even before a light verb.
  check("\xd8\xa7\xdb\x8c\xd9\x86\xd8\xac\xd8\xa7 \xd9\x87\xd8\xb1\xd8\xac \xd9\x88 \xd9\x85\xd8\xb1\xd8\xac \xd8\xb4\xd8\xaf",
        "\xd8\xa7\xdb\x8c\xd9\x86\xd8\xac\xd8\xa7 \xd9\x87\xd8\xb1\xd8\xac \xd9\x88 \xd9\x85\xd8\xb1\xd8\xac \xd8\xb4\xd8\xaf");  // اینجا هرج و مرج شد

  // But a real "merge" light-verb phrase elsewhere does convert.
  check("\xd8\xa7\xdb\x8c\xd9\x86 \xd8\xa8\xd8\xb1\xd9\x86\xda\x86 \xd8\xb1\xd9\x88 \xd9\x85\xd8\xb1\xd8\xac \xda\xa9\xd9\x86",
        "\xd8\xa7\xdb\x8c\xd9\x86 branch \xd8\xb1\xd9\x88 merge \xda\xa9\xd9\x86");  // این برنچ رو مرج کن

  check("", "");
  check("hello world", "hello world");

  if (!fails) printf("all passed\n");
  return fails != 0;
}
